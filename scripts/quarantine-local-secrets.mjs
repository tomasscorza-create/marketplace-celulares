import { existsSync, mkdirSync, renameSync, writeFileSync } from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
const stamp = new Date().toISOString().replace(/[:.]/g, "-");
const quarantineDir = path.join(rootDir, ".local-quarantine", stamp);

const targets = [
  ".env.local",
  ".supabase-secrets.env",
  "supabase/.temp",
];

function moveTarget(relativePath) {
  const source = path.join(rootDir, relativePath);

  if (!existsSync(source)) {
    return false;
  }

  const destination = path.join(quarantineDir, relativePath);
  mkdirSync(path.dirname(destination), { recursive: true });
  renameSync(source, destination);

  return true;
}

mkdirSync(quarantineDir, { recursive: true });

const moved = [];

for (const target of targets) {
  if (moveTarget(target)) {
    moved.push(target);
  }
}

writeFileSync(
  path.join(rootDir, ".env.local"),
  [
    "# Safe local environment generated by scripts/quarantine-local-secrets.mjs",
    "VITE_ENABLE_REMOTE_BACKEND=false",
    "VITE_SUPABASE_URL=",
    "VITE_SUPABASE_ANON_KEY=",
    "VITE_SUPABASE_PROJECT_REF=",
    "VITE_PUBLIC_SITE_URL=http://localhost:5173",
    "",
  ].join("\n"),
  "utf8",
);

console.log("Local backend secrets quarantined.");
console.log(`Quarantine folder: ${path.relative(rootDir, quarantineDir).replaceAll(path.sep, "/")}`);

if (moved.length === 0) {
  console.log("No existing secret/link files were found.");
} else {
  console.log("Moved:");
  for (const item of moved) {
    console.log(`- ${item}`);
  }
}

console.log("Generated a safe .env.local with remote backend disabled.");
