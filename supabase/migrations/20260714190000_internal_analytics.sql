create or replace function public.save_analytics_consent(
  requested_acceptance boolean,
  requested_policy_version text
)
returns public.analytics_consents
language plpgsql
security definer
set search_path = public
as $$
declare
  current_user_id uuid := auth.uid();
  normalized_version text := left(trim(coalesce(requested_policy_version, '')), 40);
  saved_consent public.analytics_consents;
begin
  if current_user_id is null then
    raise exception 'Authentication required.';
  end if;

  if normalized_version = '' then
    raise exception 'Policy version is required.';
  end if;

  insert into public.analytics_consents (
    user_id,
    policy_version,
    accepted_at,
    revoked_at,
    updated_at
  )
  values (
    current_user_id,
    normalized_version,
    now(),
    case when requested_acceptance then null else now() end,
    now()
  )
  on conflict (user_id) do update
  set
    policy_version = excluded.policy_version,
    accepted_at = case
      when requested_acceptance then now()
      else public.analytics_consents.accepted_at
    end,
    revoked_at = case when requested_acceptance then null else now() end,
    updated_at = now()
  returning * into saved_consent;

  insert into public.analytics_consent_history (user_id, policy_version, action)
  values (
    current_user_id,
    normalized_version,
    case when requested_acceptance then 'accepted' else 'revoked' end
  );

  return saved_consent;
end;
$$;

revoke all on function public.save_analytics_consent(boolean, text) from public;
grant execute on function public.save_analytics_consent(boolean, text) to authenticated;

create or replace function public.record_anonymous_analytics(
  requested_event_name text,
  requested_path text,
  requested_device_type text,
  requested_os_family text,
  requested_performance_tier text,
  requested_country_code text,
  requested_region text,
  requested_city text,
  requested_referrer_domain text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  normalized_event text := lower(trim(coalesce(requested_event_name, '')));
begin
  if normalized_event not in (
    'visit', 'page_view', 'product_view', 'artisan_view', 'search',
    'filter', 'contact_click', 'signup_started'
  ) then
    raise exception 'Unsupported anonymous analytics event.';
  end if;

  insert into public.analytics_anonymous_daily (
    bucket_date,
    event_name,
    path,
    device_type,
    os_family,
    performance_tier,
    country_code,
    region,
    city,
    referrer_domain,
    total_count,
    updated_at
  )
  values (
    current_date,
    normalized_event,
    left(coalesce(nullif(trim(requested_path), ''), '/'), 240),
    requested_device_type,
    requested_os_family,
    requested_performance_tier,
    left(coalesce(nullif(trim(requested_country_code), ''), 'unknown'), 8),
    left(coalesce(nullif(trim(requested_region), ''), 'unknown'), 100),
    left(coalesce(nullif(trim(requested_city), ''), 'unknown'), 100),
    left(coalesce(nullif(trim(requested_referrer_domain), ''), 'direct'), 120),
    1,
    now()
  )
  on conflict (
    bucket_date,
    event_name,
    path,
    device_type,
    os_family,
    performance_tier,
    country_code,
    region,
    city,
    referrer_domain
  ) do update
  set
    total_count = public.analytics_anonymous_daily.total_count + 1,
    updated_at = now();
end;
$$;

