create or replace function public.handle_new_profile_analytics_consent()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  user_metadata jsonb;
  requested_consent boolean := false;
  requested_version text := '';
begin
  select raw_user_meta_data into user_metadata
  from auth.users
  where id = new.id;

  requested_consent := lower(coalesce(user_metadata ->> 'analytics_consent', 'false')) = 'true';
  requested_version := left(trim(coalesce(user_metadata ->> 'analytics_policy_version', '')), 40);

  if requested_consent and requested_version <> '' then
    insert into public.analytics_consents (user_id, policy_version, accepted_at, revoked_at, updated_at)
    values (new.id, requested_version, now(), null, now())
    on conflict (user_id) do update
    set policy_version = excluded.policy_version,
        accepted_at = now(),
        revoked_at = null,
        updated_at = now();

    insert into public.analytics_consent_history (user_id, policy_version, action)
    values (new.id, requested_version, 'accepted');
  end if;

  return new;
end;
$$;

drop trigger if exists on_profile_created_analytics_consent on public.profiles;
create trigger on_profile_created_analytics_consent
after insert on public.profiles
for each row execute function public.handle_new_profile_analytics_consent();

