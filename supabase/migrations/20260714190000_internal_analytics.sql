-- Internal, privacy-first analytics.
-- Anonymous traffic is stored only as daily aggregates. Detailed sessions and
-- events require an authenticated user with an active consent record.

create table if not exists public.analytics_consents (
  user_id uuid primary key references public.profiles (id) on delete cascade,
  policy_version text not null check (char_length(policy_version) between 1 and 40),
  accepted_at timestamptz not null default now(),
  revoked_at timestamptz,
  updated_at timestamptz not null default now(),
  constraint analytics_consents_dates_check
    check (revoked_at is null or revoked_at >= accepted_at)
);

create table if not exists public.analytics_consent_history (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,
  policy_version text not null check (char_length(policy_version) between 1 and 40),
  action text not null check (action in ('accepted', 'revoked')),
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_sessions (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references public.profiles (id) on delete cascade,
  started_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  ended_at timestamptz,
  active_seconds integer not null default 0 check (active_seconds between 0 and 31536000),
  landing_path text not null default '/' check (char_length(landing_path) <= 240),
  referrer_domain text not null default 'direct' check (char_length(referrer_domain) <= 120),
  device_type text not null check (device_type in ('computer', 'mobile', 'tablet', 'other')),
  os_family text not null check (os_family in ('windows', 'macos', 'linux', 'android', 'ios', 'ipados', 'chromeos', 'other')),
  performance_tier text not null check (performance_tier in ('high', 'medium', 'low', 'unknown')),
  classification_confidence text not null check (classification_confidence in ('high', 'medium', 'low')),
  browser_family text not null check (browser_family in ('chrome', 'safari', 'firefox', 'edge', 'opera', 'other')),
  connection_type text not null check (connection_type in ('fast', 'standard', 'slow', 'unknown')),
  screen_size text not null check (screen_size in ('small', 'medium', 'large')),
  country_code text not null default 'unknown' check (char_length(country_code) <= 8),
  region text not null default 'unknown' check (char_length(region) <= 100),
  city text not null default 'unknown' check (char_length(city) <= 100),
  timezone text not null default 'unknown' check (char_length(timezone) <= 80),
  classifier_version text not null check (char_length(classifier_version) <= 30),
  created_at timestamptz not null default now()
);

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.analytics_sessions (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
