create or replace function public.record_catalog_activity_event_v1(
  requested_artisan_id uuid default null,
  requested_category_id uuid default null,
  requested_product_id uuid default null,
  requested_search_term text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_search_term text;
begin
  if auth.uid() is null or not exists (
    select 1
    from public.analytics_consents consent
    where consent.user_id = auth.uid()
      and consent.revoked_at is null
      and consent.policy_version = '2026-07-analytics-v1'
  ) then
    return;
  end if;

  -- Search actions are counted by the new analytics event without retaining
  -- their free-text value. Keep the legacy parameter for API compatibility.
  v_search_term := null;

  if requested_artisan_id is null
    and requested_category_id is null
    and requested_product_id is null
    and v_search_term is null then
    return;
  end if;

  insert into public.catalog_activity_events (
    user_id,
    artisan_id,
    category_id,
    product_id,
    search_term
  )
  values (
    auth.uid(),
    requested_artisan_id,
    requested_category_id,
    requested_product_id,
    v_search_term
  );
end;
$$;

